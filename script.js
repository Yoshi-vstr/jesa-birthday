// WEBSITE INTERACTIONS
// ======================================

document.addEventListener('DOMContentLoaded', () => {
  const welcome = document.getElementById('welcome');
  const bookScreen = document.getElementById('bookScreen');
  const pageContainer = document.getElementById('pageContainer');
  const prevBtn = document.getElementById('prevBtn');
  const nextBtn = document.getElementById('nextBtn');
  const counter = document.getElementById('pageCounter');
  const popup = document.getElementById('popup');
  const popupContent = document.getElementById('popupContent');

  let currentPage = 0;
  let busy = false;
  let wished = false;
  const collected = new Set();

  const isMobile = () => window.innerWidth <= 650;
  const step = () => isMobile() ? 1 : 2;

  // POPUP

  function showPopup(title, content, letter = false) {
    popupContent.replaceChildren();

    const heading = document.createElement('h3');
    heading.textContent = title;

    const message = document.createElement('div');
    message.className = letter ? 'letter-text' : 'popup-message';
    message.textContent = content;

    popupContent.append(heading, message);
    popup.classList.remove('hidden');
  }

  function closePopup() {
    popup.classList.add('hidden');
  }

  // MINI GAME

  function updateGame() {
    const count = document.getElementById('gameCount');
    const result = document.getElementById('gameResult');

    if (!count || !result) return;

    count.textContent = `${collected.size} / 5 hearts collected`;

    if (collected.size === 5) {
      result.textContent =
        'You found them all! Every heart is a reminder that you are loved. ♡';
    }
  }

  function buildGame() {
    const area = document.getElementById('gameArea');
    if (!area) return;

    area.replaceChildren();

    for (let i = 0; i < 9; i++) {
      const button = document.createElement('button');

      button.type = 'button';
      button.className = 'game-heart';
      button.dataset.index = String(i);
      button.textContent = i < 5 ? '♥' : '✧';

      if (collected.has(i)) {
        button.disabled = true;
        button.classList.add('collected');
      }

      area.append(button);
    }

    updateGame();
  }

  // RENDER PAGES

  function render() {
    const visible = step();

    pageContainer.innerHTML = pages
      .slice(currentPage, currentPage + visible)
      .map(html => `<article class="page">${html}</article>`)
      .join('');

    const end = Math.min(currentPage + visible, pages.length);

    counter.textContent =
      currentPage + 1 === end
        ? `${end} / ${pages.length}`
        : `${currentPage + 1}–${end} / ${pages.length}`;

    prevBtn.disabled = currentPage === 0;
    nextBtn.disabled = end >= pages.length;

    if (wished) {
      const cake = document.getElementById('birthdayCake');
      const message = document.getElementById('wishMessage');
      const button = document.getElementById('blowCandles');

      if (cake && message && button) {
        cake.textContent = '💗';
        message.textContent =
          'Wish made! May all your beautiful dreams come true. ♡';

        button.disabled = true;
        button.textContent = 'Wish Made ♡';
      }
    }

    buildGame();
  }

  // PAGE TURN

  function turn(direction) {
    if (busy) return;

    const next = currentPage + direction * step();

    if (next < 0 || next >= pages.length) return;

    busy = true;

    pageContainer.classList.add(
      direction > 0 ? 'turn-next' : 'turn-prev'
    );

    setTimeout(() => {
      currentPage = next;
      pageContainer.classList.remove('turn-next', 'turn-prev');
      render();
      busy = false;
    }, 400);
  }

  // OPEN GIFT

  const giftButton = document.getElementById('openGift');

  giftButton.addEventListener('click', () => {
    welcome.classList.add('hidden');
    bookScreen.classList.remove('hidden');
    currentPage = 0;
    render();
    window.scrollTo(0, 0);
  });

  // NAVIGATION

  prevBtn.addEventListener('click', () => turn(-1));
  nextBtn.addEventListener('click', () => turn(1));

  // PAGE INTERACTIONS

  pageContainer.addEventListener('click', event => {
    const target = event.target;

    if (!(target instanceof Element)) return;

    // NINE WISHES
    const wish = target.closest('[data-wish-index]');

    if (wish) {
      const item = birthdayWishes[Number(wish.dataset.wishIndex)];

      if (item) {
        showPopup(`${item[0]} ♡`, item[1]);
      }
      return;
    }

    // SECRET HEARTS
    const secret = target.closest('[data-secret]');

    if (secret) {
      showPopup(
        'A Little Reminder ♡',
        secretMessages[Number(secret.dataset.secret)]
      );
      return;
    }

    // SPECIAL SURPRISES
    const surprise = target.closest('[data-surprise]');

    if (surprise) {
      const index = Number(surprise.dataset.surprise);

      showPopup(
        index === 0 ? 'A Surprise From Japan 🎁' : 'A Little Promise ♡',
        surprises[index]
      );
      return;
    }

    // LETTER
    if (target.closest('#openEnvelope')) {
      showPopup('To My Dearest Jesa ♡', birthdayLetter, true);
      return;
    }

    // CAKE
    const blowButton = target.closest('#blowCandles');

    if (blowButton && !wished) {
      wished = true;

      document.getElementById('birthdayCake').textContent = '💗';
      document.getElementById('wishMessage').textContent =
        'Wish made! May all your beautiful dreams come true. ♡';

      blowButton.disabled = true;
      blowButton.textContent = 'Wish Made ♡';

      showPopup(
        'Happy Birthday, Jesa! ♡',
        'May this year be gentle, joyful, and full of beautiful surprises. ♡'
      );
      return;
    }

    // MINI GAME
    const gameHeart = target.closest('.game-heart');

    if (gameHeart) {
      const index = Number(gameHeart.dataset.index);

      if (index < 5 && !collected.has(index)) {
        collected.add(index);
        gameHeart.disabled = true;
        gameHeart.classList.add('collected');
        updateGame();

        if (collected.size === 5) {
          showPopup(
            'You Found Them All! ♡',
            'Five hearts, a thousand happy birthday wishes, and so many more memories ahead! ♡'
          );
        }
      }
    }
  });

  // CLOSE POPUP

  document.getElementById('closePopup')
    .addEventListener('click', closePopup);

  popup.addEventListener('click', event => {
    if (event.target === popup) closePopup();
  });

  // KEYBOARD

  document.addEventListener('keydown', event => {
    if (event.key === 'Escape') closePopup();

    if (
      bookScreen.classList.contains('hidden') ||
      !popup.classList.contains('hidden')
    ) return;

    if (event.key === 'ArrowRight') turn(1);
    if (event.key === 'ArrowLeft') turn(-1);
  });

  // RESPONSIVE

  let wasMobile = isMobile();

  window.addEventListener('resize', () => {
    if (wasMobile === isMobile()) return;

    wasMobile = isMobile();

    if (!wasMobile) {
      currentPage = Math.floor(currentPage / 2) * 2;
    }

    if (!bookScreen.classList.contains('hidden')) render();
  });
});
