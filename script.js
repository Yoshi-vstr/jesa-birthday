function photo(filename, caption, wide = false) {
  return `
    <figure class="polaroid ${wide ? 'wide' : ''}">
      <img
        src="images/${filename}"
        alt="${caption}"
        loading="lazy"
        onerror="this.style.display='none';this.nextElementSibling.style.display='grid';"
      >
      <div class="photo-placeholder" style="display:none;">
        ♡ Add your photo here ♡
      </div>
      <figcaption>${caption}</figcaption>
    </figure>
  `;
}

